"""Build ``REPORT.md`` from the append-only JSONL results. Nothing in the report is typed by hand."""

from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Any


def read_lines(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def percentile(values: list[float], q: float) -> float | None:
    """Nearest-rank percentile (no interpolation): the smallest value with at least q% at or below it."""
    if not values:
        return None
    ordered = sorted(values)
    rank = max(1, math.ceil(q / 100 * len(ordered)))
    return ordered[rank - 1]


def load_prices(path: Path) -> dict[str, dict[str, Any]]:
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return data.get("models", {})


def _cost(lines: list[dict[str, Any]], prices: dict[str, dict[str, Any]], model: str) -> str:
    reported = [ln.get("cost_usd") for ln in lines if ln.get("llm_calls")]
    if reported and all(c is not None for c in reported):
        return f"${sum(reported):.6f} (provider-reported)"
    model_id = model.split(":", 1)[-1]
    price = prices.get(model_id)
    if price:
        p_in = sum(ln.get("prompt_tokens", 0) for ln in lines)
        p_out = sum(ln.get("completion_tokens", 0) for ln in lines)
        usd = p_in / 1e6 * price["input_per_mtok"] + p_out / 1e6 * price["output_per_mtok"]
        return f"${usd:.6f} (tokens x data/prices.json)"
    return "n/a (no reported cost, no price entry)"


def model_rows(lines: list[dict[str, Any]], prices: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    groups: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for ln in lines:
        groups[(ln["suite"], ln["model"])].append(ln)
    rows = []
    for (suite, model), group in sorted(groups.items()):
        graded = [g for g in group if g["outcome"] in ("pass", "fail")]
        passed = [g for g in graded if g["outcome"] == "pass"]
        crit = [g for g in graded if g.get("critical")]
        crit_pass = [g for g in crit if g["outcome"] == "pass"]
        answered = [g for g in group if g.get("llm_calls")]
        lat = [g["latency_ms"] for g in graded]
        rows.append(
            {
                "suite": suite,
                "model": model,
                "runs": len(group),
                "graded": len(graded),
                "passed": len(passed),
                "accuracy": (len(passed) / len(graded)) if graded else None,
                "critical": f"{len(crit_pass)}/{len(crit)}",
                "infra_error": sum(1 for g in group if g["outcome"] == "infra_error"),
                "error": sum(1 for g in group if g["outcome"] == "error"),
                "not_run": sum(1 for g in group if g["outcome"] == "not_run"),
                "p50_ms": percentile(lat, 50),
                "p95_ms": percentile(lat, 95),
                "mean_prompt_tokens": (sum(g.get("prompt_tokens", 0) for g in answered) / len(answered))
                if answered
                else None,
                "mean_completion_tokens": (
                    sum(g.get("completion_tokens", 0) for g in answered) / len(answered)
                )
                if answered
                else None,
                "cost": _cost(answered, prices, model),
                "dropped_citations": sum(g.get("citations_dropped", 0) for g in group),
                "kept_citations": sum(g.get("citations_kept", 0) for g in group),
                "run_ids": sorted({g["run_id"] for g in group}),
            }
        )
    return rows


def _fmt(v: Any, digits: int = 0) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.{digits}f}"
    return str(v)


def build_report(results_dir: Path, prices_path: Path) -> str:
    prices = load_prices(prices_path)
    lines = read_lines(results_dir / "agent.jsonl") + read_lines(results_dir / "rag.jsonl")
    verifier = read_lines(results_dir / "verifier.jsonl")
    out = [
        "# Eval report",
        "",
        "Generated by `python -m llm_toolkit.eval report` from the JSONL files in this folder. Do not edit by hand.",
        "",
        "Accuracy counts only `pass` and `fail`. Infrastructure errors (429, 5xx, timeouts, deadline) and",
        "cases that were not run because the request budget ran out are listed separately.",
        "Latency is per case (sum of the case's LLM calls, including retries), nearest-rank percentiles.",
        "",
        "## Model runs",
        "",
    ]
    if not lines:
        out += ["No live model runs are recorded yet.", ""]
    else:
        out += [
            "| suite | model | accuracy | critical | infra err | error | not run | p50 ms | p95 ms | prompt tok | completion tok | cost |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        rows = model_rows(lines, prices)
        for r in rows:
            acc = f"{r['passed']}/{r['graded']}" + (
                f" ({r['accuracy']:.0%})" if r["accuracy"] is not None else ""
            )
            out.append(
                f"| {r['suite']} | `{r['model']}` | {acc} | {r['critical']} | {r['infra_error']} | {r['error']} | "
                f"{r['not_run']} | {_fmt(r['p50_ms'])} | {_fmt(r['p95_ms'])} | {_fmt(r['mean_prompt_tokens'])} | "
                f"{_fmt(r['mean_completion_tokens'])} | {r['cost']} |"
            )
        out.append("")
        for r in rows:
            if r["suite"] == "rag":
                out.append(
                    f"- RAG `{r['model']}`: {r['kept_citations']} quotes verified, {r['dropped_citations']} dropped "
                    "by the verifier (not verbatim in a retrieved chunk)."
                )
        out.append("")
        out.append("Run ids: " + ", ".join(sorted({ln["run_id"] for ln in lines})))
        out.append("")
    out += ["## Citation verifier benchmark (offline, planted defects)", ""]
    if not verifier:
        out += ["Not run yet.", ""]
    else:
        last = verifier[-1]
        out += [
            f"Latest run `{last['run_id']}` on `{last['dataset']}` ({last['answers']} answers, {last['citations']} citations):",
            "",
            f"- planted defects dropped: **{last['defects_dropped']}/{last['defects']}**",
            f"- genuine quotes kept: **{last['genuine_kept']}/{last['genuine']}**",
            f"- drops with the expected reason: {last['reason_matches']}/{last['defects']}",
            "",
            "| label | expected | correct | total |",
            "|---|---|---|---|",
        ]
        for label, s in sorted(last["by_label"].items()):
            out.append(f"| {label} | {s['expected']} | {s['correct']} | {s['total']} |")
        out.append("")
    return "\n".join(out)


def write_report(results_dir: Path, prices_path: Path) -> Path:
    path = results_dir / "REPORT.md"
    path.write_text(build_report(results_dir, prices_path) + "\n", encoding="utf-8")
    return path
